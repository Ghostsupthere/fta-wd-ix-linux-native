// Generates Engine/Source/Retail/BodyShapeData/FtaProfiles.hpp.
//
// The audited breast/butt profiles in Profiles.hpp fingerprint the retail meshes by exact vertex position. FTA's player
// models are different conversions of the same bodies (same silhouette to about a centimetre, different vertex layout), so
// none of them match. For each FTA model this reuses the retail profile's regions, curve parameters and per-vertex weights,
// transferring the weights onto FTA's own vertices (nearest retail weight within MaxDistance) and measuring FTA's bounds.
//
// Usage: genfta <out.hpp> <dumpdir> <spec.txt>
//   spec.txt lines: <dump file> <retail profile path (single backslashes)> <FTA model path>
//   dump files: uint32 count, then 6 floats per vertex (position, normal), written by the extraction script.
#include "Engine/Source/Retail/BodyShapeData/Profiles.hpp"
#include <algorithm>
#include <array>
#include <cmath>
#include <cstdint>
#include <cstdio>
#include <cstring>
#include <fstream>
#include <map>
#include <sstream>
#include <string>
#include <vector>
using namespace body_shape;

static constexpr float MaxDistance = 0.015f;
static float F(uint32_t u) { float f; std::memcpy(&f, &u, 4); return f; }
static uint32_t U(float f) { if (f == 0) f = 0; uint32_t u; std::memcpy(&u, &f, 4); return u; }
static std::string Esc(const std::string& s) { std::string o; for (char c : s) { if (c == '\\') o += "\\\\"; else o += c; } return o; }

int main(int argc, char** argv) {
    if (argc < 4) return 2;
    std::ifstream spec(argv[3]);
    std::ofstream out(argv[1]);
    out << "// GENERATED by tools/bodyshape-profiles/genfta.cpp; do not edit. See that file for what this is.\n#pragma once\n#include \"Engine/Source/Retail/BodyShapeData/Deform.hpp\"\n\nnamespace body_shape {\n\n";
    std::string rows;
    std::string line;
    int index = 0;
    while (std::getline(spec, line)) {
        if (line.empty() || line[0] == '#') continue;
        std::istringstream in(line);
        std::string dump, retail, fta;
        in >> dump >> retail;
        std::getline(in >> std::ws, fta);
        const Profile* P = nullptr;
        for (const Profile& p : Profiles) if (retail == p.path && p.mask) { P = &p; break; }
        if (!P) { std::fprintf(stderr, "%s: no masked retail profile %s\n", dump.c_str(), retail.c_str()); continue; }

        FILE* f = std::fopen((std::string(argv[2]) + "/" + dump).c_str(), "rb");
        uint32_t nv = 0;
        if (!f || std::fread(&nv, 4, 1, f) != 1) { std::fprintf(stderr, "cannot read %s\n", dump.c_str()); continue; }
        std::vector<float> v(size_t(nv) * 6);
        if (std::fread(v.data(), 4, v.size(), f) != v.size()) { std::fclose(f); continue; }
        std::fclose(f);

        // Grid of the retail weights (cell = MaxDistance).
        std::map<std::array<int, 3>, std::vector<uint32_t>> grid;
        auto cell = [&](float x, float y, float z) { return std::array<int, 3>{ int(std::floor(x / MaxDistance)), int(std::floor(y / MaxDistance)), int(std::floor(z / MaxDistance)) }; };
        for (size_t m = 0; m < P->maskSize; ++m) {
            if (!(P->mask[m].bits & 3)) continue;
            grid[cell(F(P->mask[m].x), F(P->mask[m].y), F(P->mask[m].z))].push_back(uint32_t(m));
        }

        float lo[3] = { 1e9f, 1e9f, 1e9f }, hi[3] = { -1e9f, -1e9f, -1e9f };
        std::map<std::array<uint32_t, 3>, uint32_t> weights; // unique FTA positions -> bits
        size_t breast = 0, butt = 0;
        for (uint32_t i = 0; i < nv; ++i) {
            float x = v[i * 6], y = v[i * 6 + 1], z = v[i * 6 + 2];
            if (std::isfinite(x) && std::isfinite(y) && std::isfinite(z)) {
                float p[3] = { x, y, z };
                for (int a = 0; a < 3; ++a) { lo[a] = std::fmin(lo[a], p[a]); hi[a] = std::fmax(hi[a], p[a]); }
            }
            auto c = cell(x, y, z);
            float best = MaxDistance * MaxDistance;
            int bestM = -1;
            for (int dx = -1; dx <= 1; ++dx) for (int dy = -1; dy <= 1; ++dy) for (int dz = -1; dz <= 1; ++dz) {
                auto it = grid.find({ c[0] + dx, c[1] + dy, c[2] + dz });
                if (it == grid.end()) continue;
                for (uint32_t m : it->second) {
                    float ex = F(P->mask[m].x) - x, ey = F(P->mask[m].y) - y, ez = F(P->mask[m].z) - z;
                    float d = ex * ex + ey * ey + ez * ez;
                    if (d < best) { best = d; bestM = int(m); }
                }
            }
            if (bestM < 0) continue;
            uint32_t bits = P->mask[bestM].bits;
            weights[{ U(x), U(y), U(z) }] = bits;
            breast += (bits & 1) != 0;
            butt += (bits & 2) != 0;
        }
        // Binary search order used by VertexMask: unsigned x, then y, then z (std::map already sorts that way).
        char name[32];
        std::snprintf(name, sizeof(name), "FtaMask%d", index);
        out << "inline constexpr MaskEntry " << name << "[] = {\n";
        for (const auto& [k, bits] : weights) out << "    {" << k[0] << "u," << k[1] << "u," << k[2] << "u," << bits << "u},\n";
        out << "};\n\n";
        std::fprintf(stderr, "%-34s %6u verts: %5zu weighted (%zu breast, %zu butt) of retail %zu\n", fta.c_str(), nv, weights.size(), breast, butt, P->maskSize);

        char row[2048];
        std::snprintf(row, sizeof(row),
            "    {\"%s\",{{%.9ff,%.9ff,%.9ff},{%.9ff,%.9ff,%.9ff}},{{%.9ff,%.9ff,%.9ff},{%.9ff,%.9ff,%.9ff}},{%.9ff,%.9ff,%.9ff},{%.9ff,%.9ff,%.9ff},%s,%zu,\"%s\",%s,%.3ff,%.3ff,%.3ff,%.3ff,%.3ff,%.3ff},\n",
            Esc(fta).c_str(),
            P->chest.offset.x, P->chest.offset.y, P->chest.offset.z, P->chest.scale.x, P->chest.scale.y, P->chest.scale.z,
            P->rear.offset.x, P->rear.offset.y, P->rear.offset.z, P->rear.scale.x, P->rear.scale.y, P->rear.scale.z,
            lo[0] - 0.2f, lo[1] - 0.2f, lo[2] - 0.2f, hi[0] + 0.2f, hi[1] + 0.2f, hi[2] + 0.2f,
            name, weights.size(), Esc(P->asset ? P->asset : retail).c_str(), P->rounded ? "true" : "false",
            P->chestLower, P->rearLower, P->rearBlend, P->chestBlend, P->chestUpper, P->chestUpperBlend);
        rows += row;
        ++index;
    }
    out << "inline constexpr Profile FtaProfiles[] = {\n" << rows << "};\n\n} // namespace body_shape\n";
    return 0;
}
