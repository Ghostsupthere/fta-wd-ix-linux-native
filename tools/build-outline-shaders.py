#!/usr/bin/env python3
"""Verify or regenerate the unit-outline pixel shaders (WxlUnitOutline/outline_shaders.h).

The supplied wxl-unit-outline compiles five small HLSL strings (Hlsl.hpp) at run time with D3DCompiler. The
native client never loads a compiler, so they are compiled offline with the same checksum-pinned compiler
and Wine prefix as the other visual shaders (tools/build-native-visual-shaders.py) and looked up at run time
by a 64-bit FNV-1a hash of the exact source text.
"""
import argparse
import hashlib
import json
import os
from pathlib import Path
import re
import subprocess

ROOT = Path(__file__).resolve().parent.parent
DIR = ROOT / 'WoW/Source/WorldClient/Linux/WxlUnitOutline'
HLSL = DIR / 'Hlsl.hpp'
OUT = DIR / 'outline_shaders.h'
PROFILE = 'ps_2_0'

def fnv1a(text):
    value = 0xcbf29ce484222325
    for byte in text.encode():
        value = ((value ^ byte) * 0x100000001b3) & 0xffffffffffffffff
    return value

def sources():
    """Name -> exact string value of each `const char* kXxxHLSL = "..." "...";` in Hlsl.hpp."""
    text = HLSL.read_text()
    result = {}
    for match in re.finditer(r'const char\*\s+(k\w+HLSL)\s*=\s*((?:\s*"(?:[^"\\]|\\.)*")+)\s*;', text):
        pieces = re.findall(r'"((?:[^"\\]|\\.)*)"', match.group(2))
        result[match.group(1)] = ''.join(pieces).encode().decode('unicode_escape')
    return result

def digest(data):
    return hashlib.sha256(data).hexdigest()

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--verify', action='store_true', help='check the checked-in table against Hlsl.hpp without Wine')
    parser.add_argument('--compiler-dll', type=Path, default=ROOT / '.deps/visual-shader-tools/d3dcompiler_47.dll')
    args = parser.parse_args()
    shaders = sources()
    if len(shaders) != 5:
        raise SystemExit(f'expected 5 HLSL strings in Hlsl.hpp, found {len(shaders)}: {sorted(shaders)}')
    if args.verify:
        table = OUT.read_text()
        for name, text in sorted(shaders.items()):
            if f'0x{fnv1a(text):016x}ull' not in table or f'// {name}' not in table:
                raise SystemExit(f'{name}: Hlsl.hpp changed since outline_shaders.h was generated')
        print(f'Verified {len(shaders)} outline shaders against Hlsl.hpp')
        return
    work = ROOT / '.deps/visual-shader-tools'
    exe = work / 'compile.exe'
    manifest = json.loads((ROOT / 'Engine/Source/ModernAssets/WxlVisuals/shader_manifest.json').read_text())
    if not args.compiler_dll.is_file() or digest(args.compiler_dll.read_bytes()) != manifest['compiler_sha256']:
        raise SystemExit('Missing or mismatched offline compiler DLL; see Engine/Source/ModernAssets/WxlVisuals/SOURCE.md')
    if not exe.is_file():
        subprocess.run(['x86_64-w64-mingw32-g++', '-std=c++17', '-static', str(ROOT / 'tools/wxl_compile_shader.cpp'),
                        '-ld3dcompiler', '-o', str(exe)], check=True)
    env = dict(os.environ, WINEPREFIX=str(work / 'wine'), WINEDEBUG='-all',
               WINEDLLOVERRIDES='d3dcompiler_47=n;mscoree,mshtml=')
    lines = ['// Generated by tools/build-outline-shaders.py from Hlsl.hpp; do not edit.',
             '// Offline-compiled ps_2_0 bytecode, found at run time by FNV-1a of the exact HLSL text.',
             '#pragma once', '#include <cstddef>', '#include <cstdint>', 'namespace wxl_outline_shaders {',
             'struct Entry { uint64_t sourceHash; const unsigned char* bytes; size_t size; };']
    entries = []
    for name, text in sorted(shaders.items()):
        source = work / f'{name}.hlsl'
        source.write_text(text)
        binary = work / f'{name}.bin'
        result = subprocess.run(['wine', str(exe), 'Z:' + str(source), PROFILE, 'Z:' + str(binary)],
                                env=env, cwd=work, capture_output=True, text=True)
        if result.returncode:
            raise SystemExit(name + ': ' + result.stdout + result.stderr)
        blob = binary.read_bytes()
        values = ','.join(f'0x{b:02x}' for b in blob)
        lines.append(f'// {name} ({len(blob)} bytes, sha256 {digest(blob)})')
        lines.append(f'alignas(4) inline constexpr unsigned char g_{name}[] = {{{values}}};')
        entries.append(f'    {{0x{fnv1a(text):016x}ull, g_{name}, sizeof(g_{name})}},')
        print(name, len(blob), flush=True)
    lines.append('inline constexpr Entry kEntries[] = {')
    lines.extend(entries)
    lines.append('};')
    lines.append('}')
    OUT.write_text('\n'.join(lines) + '\n')

if __name__ == '__main__':
    main()
